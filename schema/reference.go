// namespaces are the module namespaces the reference has a part for, with
// the part's title and what a module of it is.
var namespaces = []struct{ ns, title, kind, file string }{
	{module.Handlers, "Handlers", "handler", "handlers.md"},
	{module.Middlewares, "Middleware", "middleware", "middleware.md"},
}

// Reference returns the config reference, as Markdown: every field of the
// native config and of the modules registered, with its type, its default
// and its description, built from the same types and tags as the schema,
// in chapters, each with the text and the examples in schema/doc.
// docs/reference/config.md holds it for the modules in modules/standard.
// It fails when a field or a module has no description, or a chapter's
// example does not convert.
func Reference() ([]byte, error) {
	r := &reference{anchors: map[reflect.Type]*section{}}
	r.walk(reflect.TypeFor[config.Config](), "", "config")
	config := r.sections
	r.sections = nil
	byChapter := map[string][]*section{}
	for _, s := range config[1:] {
		field := s.paths[0]
		if i := strings.IndexAny(field, ".["); i >= 0 {
			field = field[:i]
		}
		byChapter[field] = append(byChapter[field], s)
	}
	type part struct {
		title, anchor string
		chapter       *chapter
		sections      []*section
	}
	var parts []part
	for _, f := range chapters {
		c, err := readChapter(f.file)
		if err != nil {
			return nil, err
		}
		parts = append(parts, part{f.title, f.anchor, c, byChapter[f.field]})
		delete(byChapter, f.field)
	}
	for field := range byChapter {
		r.missing = append(r.missing, "a chapter for "+field)
	}
	for _, n := range namespaces {
		c, err := readChapter(n.file)
		if err != nil {
			return nil, err
		}
		p := part{title: n.title, anchor: strings.ToLower(n.title), chapter: c}
		for _, info := range module.Namespace(n.ns) {
			if info.Doc == "" {
				r.missing = append(r.missing, "module "+info.ID)
			}
			r.module = info.Name()
			s := r.walk(reflect.TypeOf(info.New()).Elem(), "", strings.ReplaceAll(info.ID, ".", "-"))
			s.title = "`" + info.Name() + "`"
			s.doc = info.Doc
			if m, err := readChapter("modules/" + info.Name() + ".md"); err == nil {
				s.chapter = m
			} else if _, standard := standardModules[info.Name()]; standard {
				return nil, err
			}
			r.module = ""
		}
		p.sections, r.sections = r.sections, nil
		parts = append(parts, p)
	}
	if len(r.missing) > 0 {
		return nil, errors.New("schema: no description for " + strings.Join(r.missing, ", "))
	}

	var buf bytes.Buffer
	buf.WriteString(referenceHead)
	buf.WriteString("\n## Contents\n\n- [The config](#the-config)\n")
	for _, p := range parts {
		fmt.Fprintf(&buf, "- [%s](#%s)", p.title, p.anchor)
		var subs []string
		for _, s := range p.sections {
			if s.module == "" || s.title != "" {
				subs = append(subs, fmt.Sprintf("[%s](#%s)", s.heading(), s.anchor))
			}
		}
		if len(subs) > 0 {
			fmt.Fprintf(&buf, ": %s", strings.Join(subs, ", "))
		}
		buf.WriteString("\n")
	}
	top, err := readChapter("config.md")
	if err != nil {
		return nil, err
	}
	buf.WriteString("\n## The config\n")
	if err := top.write(&buf); err != nil {
		return nil, err
	}
	r.write(&buf, config[:1], false)
	for _, p := range parts {
		fmt.Fprintf(&buf, "\n<a id=\"%s\"></a>\n\n## %s\n", p.anchor, p.title)
		if err := p.chapter.write(&buf); err != nil {
			return nil, err
		}
		if err := r.writeAll(&buf, p.sections); err != nil {
			return nil, err
		}
	}
	return buf.Bytes(), nil
}

const referenceHead = `# Config reference

[English](config.md) | [简体中文](config.zh-CN.md)

<!-- Generated by schema.Reference from fit's config types and modules, and the chapters in
schema/doc; do not edit. Regenerate with: go test ./schema -update -->

Every field of fit's native config, schema version 1, and of the params of the modules in
` + "`modules/standard`" + `: what each part of a config is for, an example of it, and a table of
its fields, with each field's type, default and description. A config may be written as a
[Caddyfile](caddyfile.md), in [YAML](yaml.md) or in [JSON](json.md); YAML and JSON have exactly the
fields below, and a Caddyfile converts to them. [Configuration](../configuration.md) says how a
config is loaded, checked and changed.

How to read the tables: a field left out takes its default, when it has one; a duration is a
string such as ` + "`\"1.5s\"`" + ` or ` + "`\"2m\"`" + `; an integer's bounds follow its type; ` + "`object`" + `
links to the object's own table; a field marked Required must be written; a field marked
Deprecated is an old name that still works, with a warning. The
[JSON Schema](../../schema/fit.schema.json) says the same for editors, and ` + "`fit validate`" + ` checks
a config against it and more.
`

// A section is a struct type's table: the config's, a module's params, or
// a struct within them.
type section struct {
	anchor string
	title  string // for a module, its name; otherwise the paths it is at
	doc    string
	paths  []string
	rows   [][4]string
	// module is the module whose params the section is part of, if any.
	module string
	// chapter is the text and examples of a module's, from schema/doc.
	chapter *chapter
}

// heading returns the section's title: a module's name, or the first path
// it is at, with the module whose params hold it.
func (s *section) heading() string {
	if s.title != "" {
		return s.title
	}
	for _, p := range s.paths {
		if p != "" {
			if s.module != "" {
				return "`" + p + "` in `" + s.module + "`"
			}
			return "`" + p + "`"
		}
	}
	return ""
}

type reference struct {
	anchors  map[reflect.Type]*section
	sections []*section
	missing  []string
	module   string // the module whose params are being walked
}

// walk makes the section of struct type t, at path, and those of the
// structs its fields hold, after it.
func (r *reference) walk(t reflect.Type, path, anchor string) *section {
	s := &section{anchor: anchor, paths: []string{path}, module: r.module}
	if t.Name() != "" {
		r.anchors[t] = s
	}
	r.sections = append(r.sections, s)
	for _, f := range config.Fields(t) {
		if f.Self {
			continue
		}
		fpath := join(path, f.Name)
		if f.Doc == "" {
			r.missing = append(r.missing, t.String()+"."+f.Name)
		}
		typ := r.typeName(f.Type, &f, fpath)
		def := ""
		if f.Default != "" {
			def = "`" + f.Default + "`"
		}
		doc := f.Doc
		if f.Required {
			doc = "Required. " + doc
		}
		s.rows = append(s.rows, [4]string{"`" + f.Name + "`", typ, def, doc})
		for _, old := range f.Renamed {
			s.rows = append(s.rows, [4]string{"`" + old + "`", "", "", fmt.Sprintf("Deprecated: renamed `%s`; the old name goes in config version 2.", f.Name)})
		}
	}
	return s
}

// typeName says what type t is, for field f at path, linking to the
// section of a struct, which it makes when it is the first to hold it.
func (r *reference) typeName(t reflect.Type, f *config.Field, path string) string {
	switch {
	case t == valueType:
		return "any"
	case t == config.DurationType:
		return "duration"
	case t == moduleRefType:
		for _, n := range namespaces {
			if n.ns == f.Module {
				return fmt.Sprintf("[%s](#%s)", n.kind, strings.ToLower(n.title))
			}
		}
		return "module"
	}
	switch t.Kind() {
	case reflect.Pointer:
		return r.typeName(t.Elem(), f, path)
	case reflect.Struct:
		if s, ok := r.anchors[t]; ok {
			s.paths = append(s.paths, path)
			return fmt.Sprintf("[object](#%s)", s.anchor)
		}
		anchor := strings.ReplaceAll(strings.ToLower(t.String()), ".", "-")
		if t.Name() == "" {
			anchor = strings.NewReplacer(".", "-", "[]", "", "*", "").Replace(path)
			if r.module != "" {
				anchor = r.module + "-" + anchor
			}
		}
		// The section goes after the one being made, which r.walk
		// appended first.
		r.walk(t, path, anchor)
		return fmt.Sprintf("[object](#%s)", anchor)
	case reflect.Slice:
		return "list of " + r.typeName(t.Elem(), f, path+"[]")
	case reflect.Map:
		return "object of " + r.typeName(t.Elem(), nil, path+".*")
	case reflect.String:
		if f != nil && len(f.Enum) > 0 {
			return "string: " + "`" + strings.Join(f.Enum, "`, `") + "`"
		}
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		return withBounds("integer", f, t.Kind() >= reflect.Uint)
	case reflect.Float32, reflect.Float64:
		return withBounds("number", f, false)
	}
	panic(fmt.Sprintf("schema: unsupported type %s", t))
}

func withBounds(name string, f *config.Field, unsigned bool) string {
	var lo, hi *float64
	if f != nil {
		lo, hi = f.Min, f.Max
	}
	if lo == nil && unsigned {
		zero := 0.0
		lo = &zero
	}
	num := func(v float64) string { return strconv.FormatFloat(v, 'f', -1, 64) }
	switch {
	case lo != nil && hi != nil && *lo == *hi:
		return name + ", " + num(*lo)
	case lo != nil && hi != nil:
		return fmt.Sprintf("%s, %s to %s", name, num(*lo), num(*hi))
	case lo != nil:
		return fmt.Sprintf("%s, %s or more", name, num(*lo))
	case hi != nil:
		return fmt.Sprintf("%s, %s or less", name, num(*hi))
	}
	return name
}

func join(path, name string) string {
	if path == "" {
		return name
	}
	return path + "." + name
}

// writeAll writes sections, each with its heading.
func (r *reference) writeAll(buf *bytes.Buffer, sections []*section) error {
	for _, s := range sections {
		if err := r.write(buf, []*section{s}, true); err != nil {
			return err
		}
	}
	return nil
}

// write writes sections: a heading, unless heading is false, where else
// the object is, its description, a module's chapter and the table.
func (r *reference) write(buf *bytes.Buffer, sections []*section, heading bool) error {
	for _, s := range sections {
		var at []string
		for _, p := range s.paths {
			if p != "" {
				at = append(at, "`"+p+"`")
			}
		}
		if s.title == "" && len(at) > 0 {
			at = at[1:]
		}
		if heading {
			fmt.Fprintf(buf, "\n<a id=\"%s\"></a>\n\n### %s\n", s.anchor, s.heading())
		}
		if len(at) > 0 {
			fmt.Fprintf(buf, "\nAlso at %s.\n", strings.Join(at, ", "))
		}
		if s.doc != "" {
			fmt.Fprintf(buf, "\n%s\n", s.doc)
		}
		if s.chapter != nil {
			if err := s.chapter.write(buf); err != nil {
				return err
			}
		}
		if len(s.rows) == 0 {
			buf.WriteString("\nIt has no fields: `{}` turns it on.\n")
			continue
		}
		buf.WriteString("\n| Field | Type | Default | Description |\n| --- | --- | --- | --- |\n")
		for _, row := range s.rows {
			for j := range row {
				row[j] = strings.ReplaceAll(row[j], "|", `\|`)
			}
			fmt.Fprintf(buf, "| %s |\n", strings.Join(row[:], " | "))
		}
	}
	return nil
}
