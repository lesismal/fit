// TemplateDir returns the directory template in format, "fit", "yaml" or
// "json": its files' contents by their paths in the directory.
func TemplateDir(format string) (map[string][]byte, error) {
	if err := checkFormat(format); err != nil {
		return nil, err
	}
	ext := map[string]string{"fit": ".conf", "yaml": ".yaml", "json": ".json"}[format]
	out := map[string][]byte{}
	for _, f := range dirFiles {
		root := f.t.object(reflect.TypeFor[config.Config](), "", nil)
		var members []*tnode
		for _, m := range root.children {
			if slices.Contains(f.fields, m.name) {
				members = append(members, m)
			}
		}
		out[f.name+ext] = writeTemplate(format, append(slices.Clip(dirHead), f.about...), members)
	}
	return out, nil
}
