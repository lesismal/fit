// Package build builds fit with modules of other modules besides its own,
// as fit build does, the way xcaddy builds Caddy: it generates a main
// package that imports fit's command line, the modules and providers fit
// ships with (unless told to leave them out) and the modules asked for, and
// builds it with the go command into a binary. A module registers itself in
// an init function, so importing its package is all it takes; see
// docs/modules.md for how to write one.
package build

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"strings"
)

// FitModule is fit's own module path.
const FitModule = "github.com/lesismal/fit"

// Standard are the packages a build imports unless told to leave them out:
// every handler and middleware fit ships with, and every provider.
var Standard = []string{
	FitModule + "/modules/standard",
	FitModule + "/provider/standard",
}

// NoVersion is the version a module replaced by a directory is required at.
const NoVersion = "v0.0.0-00010101000000-000000000000"

// Module is a Go module to build in: its path, which is also the package
// imported, so the module's root must be a package that registers its
// modules; and the version to require, or the directory to build it from.
type Module struct {
	Path    string
	Version string
	Dir     string
}

// ParseModule parses a module as fit build's -with takes it: path,
// path@version, or path=dir, for a module whose source is in dir.
func ParseModule(s string) (Module, error) {
	var m Module
	s, m.Dir, _ = strings.Cut(s, "=")
	m.Path, m.Version, _ = strings.Cut(s, "@")
	switch {
	case m.Path == "" || strings.ContainsAny(m.Path, " \t"):
		return m, fmt.Errorf("-with %q: no module path", s)
	case m.Dir != "" && m.Version != "":
		return m, fmt.Errorf("-with %s: a version and a directory both", m.Path)
	}
	return m, nil
}

// Options are what a build makes.
type Options struct {
	// Output is the binary to write.
	Output string
	// Fit is the fit to build on: a version of fit's module, or a
	// directory holding its source. Its Path is ignored.
	Fit Module
	// With are the modules to build in besides fit's.
	With []Module
	// Without are packages of Standard to leave out.
	Without []string
	// Version is what the binary's fit version says.
	Version string
	// Keep, when set, is the directory the main module is generated in and
	// kept; otherwise a temporary one is, and removed.
	Keep string
	// Stderr hears the go command.
	Stderr io.Writer
}

// Imports returns the packages the main package imports besides fit's
// command line: Standard less without, then the modules of with.
func Imports(with []Module, without []string) ([]string, error) {
	for _, w := range without {
		if !slices.Contains(Standard, w) {
			return nil, fmt.Errorf("-without %s: it is none of %s", w, strings.Join(Standard, ", "))
		}
	}
	var imports []string
	for _, s := range Standard {
		if !slices.Contains(without, s) {
			imports = append(imports, s)
		}
	}
	for _, m := range with {
		if !slices.Contains(imports, m.Path) {
			imports = append(imports, m.Path)
		}
	}
	return imports, nil
}

// MainSource returns the source of the main package of a build importing
// imports.
func MainSource(imports []string) []byte {
	var b bytes.Buffer
	b.WriteString(`// Code generated by fit build. DO NOT EDIT.

// Command fit is fit, built with the modules imported below.
package main

import (
	"os"

	"github.com/lesismal/fit/cli"
`)
	for _, p := range imports {
		fmt.Fprintf(&b, "\t_ %q\n", p)
	}
	b.WriteString(`)

// version is fit's version, set by fit build.
var version string

func main() {
	cli.Version = version
	os.Exit(cli.Main(os.Args[1:], os.Stdout, os.Stderr))
}
`)
	return b.Bytes()
}

// Build generates the main module o describes and builds it into
// o.Output, with the go command found on PATH, in the environment it is
// given: GOOS and GOARCH there make a binary for another system.
func Build(ctx context.Context, o Options) error {
	if o.Output == "" {
		return errors.New("no output")
	}
	if o.Fit.Version == "" && o.Fit.Dir == "" {
		return errors.New("no fit to build on: name a version or a directory")
	}
	imports, err := Imports(o.With, o.Without)
	if err != nil {
		return err
	}
	output, err := filepath.Abs(o.Output)
	if err != nil {
		return err
	}
	stderr := o.Stderr
	if stderr == nil {
		stderr = io.Discard
	}
	dir := o.Keep
	if dir == "" {
		if dir, err = os.MkdirTemp("", "fit-build-"); err != nil {
			return err
		}
		defer os.RemoveAll(dir)
	} else if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(dir, "main.go"), MainSource(imports), 0o644); err != nil {
		return err
	}
	_ = os.Remove(filepath.Join(dir, "go.mod"))
	_ = os.Remove(filepath.Join(dir, "go.sum"))

	gocmd := func(args ...string) error {
		cmd := exec.CommandContext(ctx, "go", args...)
		cmd.Dir = dir
		// The module is the build's own: no workspace, and its go.mod is
		// what it needs, whatever the environment says.
		cmd.Env = append(os.Environ(), "GOWORK=off", "GOFLAGS=-mod=mod")
		cmd.Stdout, cmd.Stderr = stderr, stderr
		if err := cmd.Run(); err != nil {
			return fmt.Errorf("go %s: %w", strings.Join(args, " "), err)
		}
		return nil
	}
	if err := gocmd("mod", "init", "fitbuild"); err != nil {
		return err
	}
	require := func(m Module) error {
		if m.Dir != "" {
			abs, err := filepath.Abs(m.Dir)
			if err != nil {
				return err
			}
			return gocmd("mod", "edit", "-require", m.Path+"@"+NoVersion, "-replace", m.Path+"="+abs)
		}
		version := m.Version
		if version == "" {
			version = "latest"
		}
		return gocmd("get", m.Path+"@"+version)
	}
	fit := o.Fit
	fit.Path = FitModule
	if err := require(fit); err != nil {
		return err
	}
	for _, m := range o.With {
		if err := require(m); err != nil {
			return err
		}
	}
	if err := gocmd("mod", "tidy"); err != nil {
		return err
	}
	args := []string{"build", "-trimpath", "-o", output}
	if o.Version != "" {
		args = append(args, "-ldflags", "-X main.version="+o.Version)
	}
	return gocmd(append(args, ".")...)
}
